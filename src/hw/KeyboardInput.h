#pragma once

#include <Arduino.h>

#include <vector>

namespace voicerec {

// Key codes: printable keys use their unshifted ASCII character,
// non-printable keys use the control codes below.
namespace keycode {
constexpr char kBackspace = 0x08;
constexpr char kTab = 0x09;
constexpr char kEnter = 0x0D;
constexpr char kOpt = 0x11;
constexpr char kButtonG0 = 0x12;  // the side "G0" push button
constexpr char kEsc = '`';        // top-left key, printed "esc"
constexpr char kUp = ';';
constexpr char kDown = '.';
constexpr char kLeft = ',';
constexpr char kRight = '/';
}  // namespace keycode

struct KeyEvent {
    char code = 0;     // see keycode
    char text = 0;     // character with shift applied (0 for non-printable keys)
    bool fn = false;
    bool shift = false;
    bool ctrl = false;
    bool alt = false;
    bool repeat = false;  // generated by auto-repeat while the key is held
};

// Turns the raw key matrix of Cardputer / Cardputer ADV into press and auto-repeat events.
class KeyboardInput {
public:
    void update();

    bool hasEvent() const { return !events_.empty(); }
    KeyEvent nextEvent();

    // True while any key (or G0) is physically held.
    bool anyHeld() const { return !held_.empty() || g0Held_; }
    bool isHeld(char code) const;
    bool fnHeld() const { return fn_; }

    // Keys held right now will not auto-repeat (used when a key press only wakes the screen).
    void suppressHeldKeys();

private:
    struct HeldKey {
        char code;
        char text;
        uint32_t pressedAt;
        uint32_t lastRepeatAt;
        bool suppressed;
    };

    static constexpr uint32_t kRepeatDelayMs = 400;
    static constexpr uint32_t kRepeatIntervalMs = 110;

    void emit(const HeldKey& key, bool repeat);

    std::vector<HeldKey> held_;
    std::vector<KeyEvent> events_;
    bool fn_ = false;
    bool shift_ = false;
    bool ctrl_ = false;
    bool alt_ = false;
    bool g0Held_ = false;
};

}  // namespace voicerec
